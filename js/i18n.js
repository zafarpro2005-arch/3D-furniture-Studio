  try { if (DICT[localStorage.getItem('lang')]) lang = localStorage.getItem('lang'); } catch (e) {}

  function t(key, params) {
    var s = DICT[lang][key] || DICT.ru[key] || key;
    return s.replace(/\{(\w+)\}/g, function (m, k) {
      return params && params[k] !== undefined ? params[k] : m;
    });
  }

  function setLang(l) {
    if (!DICT[l]) return;
    lang = l;
    try { localStorage.setItem('lang', l); } catch (e) {}
  }

  // Подставляет тексты во все элементы с data-i18n
  function apply(doc) {
    doc.documentElement.lang = lang;
    doc.title = t((doc.body && doc.body.getAttribute('data-title')) || 'title');
    var nodes = doc.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) nodes[i].textContent = t(nodes[i].getAttribute('data-i18n'));
  }

  (root.Planner = root.Planner || {}).i18n = {
    t: t,
    setLang: setLang,
    getLang: function () { return lang; },
    apply: apply
  };
